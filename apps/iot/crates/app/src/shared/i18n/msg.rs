#[cfg(test)]
mod tests {
    use super::*;
    use iot_core::ui::font::Face;

    #[test]
    fn every_message_answers_every_language() {
        for msg in Msg::ALL {
            for lang in Lang::ALL {
                let text = msg.text(*lang);
                assert!(!text.is_empty(), "{msg:?} in {lang:?}");
                let face = Face::new();
                for ch in text.chars() {
                    assert!(face.has(ch), "{msg:?} in {lang:?} lacks {ch:?}");
                }
            }
        }
    }
}
