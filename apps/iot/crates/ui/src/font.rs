#[cfg(test)]
mod tests {
    use super::*;

    fn glyph(ch: u8) -> &'static [u8] {
        let index = usize::from(ch - 0x20) * GLYPH_COLUMNS;
        &FONT[index..index + GLYPH_COLUMNS]
    }

    #[test]
    fn every_printable_glyph_has_ink() {
        for code in 0x21..=0x7E {
            assert!(
                glyph(code).iter().any(|column| *column != 0),
                "{code:#04x} draws nothing"
            );
        }
    }

    /// The pairs a five-column cell can collapse into one shape. A table swap that made any of
    /// them equal would be a font the panel cannot read, and nothing else checks the shapes.
    #[test]
    fn glyphs_that_read_alike_are_not_the_same_bitmap() {
        for (left, right) in [
            (b'l', b'1'),
            (b'I', b'l'),
            (b'0', b'O'),
            (b'c', b'e'),
            (b'u', b'v'),
            (b'g', b'q'),
            (b'p', b'q'),
            (b'y', b'v'),
            (b'm', b'w'),
            (b'M', b'W'),
        ] {
            assert_ne!(
                glyph(left),
                glyph(right),
                "{} and {} share one bitmap",
                left as char,
                right as char
            );
        }
    }

    /// The bottom row is the descender the eight-row cell buys: these five are the letters that
    /// need it, and a face cut to seven rows would lose the tail silently.
    #[test]
    fn the_descenders_reach_the_bottom_row() {
        for &code in b"gpqyj" {
            assert!(
                glyph(code).iter().any(|column| column & 0x80 != 0),
                "{} has no descender row",
                code as char
            );
        }
    }
}
